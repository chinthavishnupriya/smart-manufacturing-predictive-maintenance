import streamlit as st

from retriever import answer_question

st.set_page_config(
    page_title="Maintenance Knowledge Assistant",
    page_icon="🔧",
    layout="wide",
)

st.title("Predictive Maintenance Knowledge Assistant")
st.caption(
    "Retrieval-augmented generation prototype: "
    "TF-IDF retrieval + evidence-grounded LLM answers"
)

st.warning(
    "Demonstration prototype. The knowledge base contains sample guidance, "
    "not verified manufacturer instructions. Follow approved manuals and "
    "site safety procedures."
)

question = st.text_input(
    "Ask a maintenance question",
    placeholder="What does the knowledge base say about increasing vibration?",
)

if st.button("Ask assistant", type="primary") and question.strip():
    with st.spinner("Searching the knowledge base and preparing an answer..."):
        result = answer_question(question)

    mode = result.get("mode", "retrieval_only")

    if mode == "gemini_rag":
        st.success("Answer generated by Gemini using retrieved evidence")
    elif mode == "llm_error":
        st.error("Gemini generation failed; review the message below")
    else:
        st.info("Retrieval-only mode: no LLM-generated answer")

    st.subheader("Assistant response")
    st.markdown(result["answer"])

    st.subheader("Retrieved evidence")
    if result["sources"]:
        st.dataframe(result["sources"], width="stretch")
    else:
        st.info("No matching source passage was found.")
